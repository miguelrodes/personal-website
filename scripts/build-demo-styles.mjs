import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import postcss from 'postcss';

// Compile only the extracted portal's utilities, then contain every selector.
// Unwrap cascade layers so the portfolio's unlayered element resets cannot win.
const result = spawnSync(process.execPath, ['node_modules/@tailwindcss/cli/dist/index.mjs',
  '-i', 'src/demo/theme.input.css', '-o', 'node_modules/.tmp/portal-tailwind.css'], { stdio: 'inherit' });
if (result.status !== 0) process.exit(result.status ?? 1);
const root = postcss.parse(readFileSync('node_modules/.tmp/portal-tailwind.css', 'utf8'));
root.walkAtRules('layer', rule => rule.nodes ? rule.replaceWith(...rule.nodes) : rule.remove());
root.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  // Tailwind emits nested relative selectors. Their parent is already contained.
  let parent = rule.parent;
  while (parent) { if (parent.type === 'rule') return; parent = parent.parent; }
  rule.selectors = rule.selectors.map(selector => {
    if ([':root', ':host', 'html', 'body', '.reporting-theme'].includes(selector.trim())) return '.aldea-demo';
    return `.aldea-demo ${selector}`;
  });
});
// The source product uses a 16px root; the surrounding portfolio uses 17px.
// Resolve rems here to preserve the extracted product's measurements.
const resolveRem = value => value.replace(/(-?\d*\.?\d+)rem\b/g, (_, n) => `${Number(n) * 16}px`);
root.walkDecls(declaration => { declaration.value = resolveRem(declaration.value); });
root.walkAtRules('media', rule => { rule.params = resolveRem(rule.params); });
const css = root.toString();
writeFileSync('src/demo/theme.generated.css', `/* Generated by npm run demo:styles. Scoped Aldea utilities. */\n${css}`);
